/**
 * 奇门吉凶格局判定（时家转盘）。判定条件依调研资料第五、六部分；各书说法不同的，逐说判定、并列标出，
 * 不替用户选边。每条结果：{ name, kind: '吉'|'凶', palace(0 为全局), says: [合于哪家说法], why, quote }。
 */
import { GAN, ganzhi } from '../../core/calendar.js';

const SANQI = ['乙', '丙', '丁'];
const JIMEN = ['开门', '休门', '生门'];
const SANYIN = ['太阴', '六合', '九地'];
const XUN_YI = ['戊', '己', '庚', '辛', '壬', '癸'];
// 六仪击刑：仪 → 所刑之宫（甲子戊刑卯震三、甲戌己刑未坤二、甲申庚刑寅艮八、甲午辛自刑离九、甲辰壬自刑巽四、甲寅癸刑巳巽四）
const XING_GONG = { 戊: 3, 己: 2, 庚: 8, 辛: 9, 壬: 4, 癸: 4 };

/** 某柱干支的天干；甲则换成该柱所在旬的旬首六仪（甲不上盘） */
function panStem(gzIdx) {
  const g = GAN[gzIdx % 10];
  return g === '甲' ? XUN_YI[Math.floor(gzIdx / 10)] : g;
}
const gzIndex = (gz) => { for (let i = 0; i < 60; i++) if (ganzhi(i) === gz) return i; return -1; };
/** 某柱在盘上可代表它的干：非甲即本干；甲则取其所遁之仪，并兼常例“戊” */
function pillarStems(gz) {
  const i = gzIndex(gz);
  return GAN[i % 10] === '甲' ? [...new Set([XUN_YI[Math.floor(i / 10)], '戊'])] : [GAN[i % 10]];
}
const PILLAR_NAME = { year: '年', month: '月', day: '日', hour: '时' };
const DOOR_WX = { 休门: '水', 死门: '土', 伤门: '木', 杜门: '木', 开门: '金', 惊门: '金', 生门: '土', 景门: '火' };
const KE5 = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
const CHONG = { 戊: '辛', 辛: '戊', 己: '壬', 壬: '己', 庚: '癸', 癸: '庚' }; // 所遁六甲相冲：子午、戌辰、申寅
const YI_ZHI = { 戊: '子', 辛: '午', 己: '戌', 壬: '辰', 庚: '申', 癸: '寅' };

export function findPatterns(C) {
  const S = C.steps, JI = S.ju.ji, xunYi = S.xun.xunYi, zhishi = C.summary.zhishiDoor;
  const out = [];
  const add = (palace, name, kind, says, why, quote) => out.push({ palace, name, kind, says, why, quote });
  const pal = (p) => {
    const P = C.palaces[p];
    const sky = P.tianStems.map((s, i) => ({ s, ji: i > 0 }));
    const earth = [{ s: P.di, ji: false }]; if (p === JI) earth.push({ s: C.palaces[5].di, ji: true });
    return { p, P, sky, earth, door: P.door, god: P.god, hasSky: (x) => sky.some((a) => a.s === x), hasEarth: (x) => earth.some((b) => b.s === x) };
  };
  const pairs = (q) => q.sky.flatMap((a) => q.earth.map((b) => [a, b]));
  // ── 伏吟、反吟（转盘为整体转动，一宫如此则八宫皆然）──
  const FY = '《宝鉴》卷一《释伏吟反吟》：“九星在本宫不动，八门在本宫不移，六甲之时是也，名曰伏吟。凡值伏吟，利主不利客，惟宜安静守常、收敛财物。”';
  const FAN = '《宝鉴》卷一：“九星临对冲之宫，八门临对冲之位，名曰反吟。凡值反吟，主客皆不宁，作事反复不定。”';
  if (S.tian.shift === 0) add(0, '星伏吟', '凶', ['各书一致'], '九星都在本宫未动，各宫天盘干与地盘干相同（即各宫奇仪伏吟）', FY);
  if (S.tian.shift === 4) add(0, '星反吟', '凶', ['各书一致'], '九星都落在对冲之宫', FAN);
  if (S.door.doorShift === 0) add(0, '门伏吟', '凶', ['各书一致'], '八门都在本宫未动', FY);
  if (S.door.doorShift === 4) add(0, '门反吟', '凶', ['各书一致'], '八门都落在对冲之宫', FAN);
  const ps = {}; for (const k of ['year', 'month', 'day', 'hour']) ps[k] = pillarStems(S.pillars[k]);
  const jiT = (x) => (x.ji ? '（寄）' : '');
  const G = (q) => `${C.palaces[q.p].gua}${q.p}宫`;

  for (const p of [4, 9, 2, 3, 7, 8, 1, 6]) {
    const q = pal(p);
    // ── 天地盘干组合类 ──
    for (const [a, b] of pairs(q)) {
      const at = `天盘${a.s}${jiT(a)}加地盘${b.s}${jiT(b)}`;
      // 青龙返首、飞鸟跌穴：常规（戊）与真甲（当旬值符之仪）
      if (b.s === '丙' && (a.s === '戊' || a.s === xunYi)) {
        const says = []; if (a.s === '戊') says.push('《秘笈》《统宗》《烟波》《宝鉴》（戊加丙）'); if (a.s === xunYi && a.s !== '戊') says.push('《烟波》《宝鉴》（当旬值符加丙）');
        add(p, '青龙返首', '吉', says, at, '《烟波》：“六甲加丙青龙返。”《宝鉴》卷一：“甲木生丙火，母倚子威，故吉。”若逢迫、墓、击、刑，吉事成凶。');
      }
      if (a.s === '丙' && (b.s === '戊' || b.s === xunYi)) {
        const says = []; if (b.s === '戊') says.push('《秘笈》《统宗》《烟波》《宝鉴》（丙加戊）'); if (b.s === xunYi && b.s !== '戊') says.push('《烟波》《宝鉴》（丙加当旬值符）');
        add(p, '飞鸟跌穴', '吉', says, at, '《烟波》：“六丙加甲鸟跌穴。”《宝鉴》卷一：“丙火还生甲木，子归母舍，不劳而得，故吉。”');
      }
      // 三奇得使：宝鉴以天地盘定；统宗、秘笈另要求临值使门
      const SHI = { 乙: ['己', '辛'], 丙: ['戊', '庚'], 丁: ['壬', '癸'] };
      if (SHI[a.s] && SHI[a.s].includes(b.s)) {
        const says = ['《烟波》《宝鉴》（三奇临所得之甲）'];
        if (q.door === zhishi) says.push('《统宗》《秘笈》（并临值使门）');
        add(p, '三奇得使', '吉', says, `${at}${q.door === zhishi ? `，又临值使${zhishi}` : `；未临值使门（${zhishi}），不合《统宗》《秘笈》严说`}`, '《烟波》：“乙逢犬马丙鼠猴，六丁玉女骑龙虎。”《宝鉴》卷一：“三奇之下得六甲之气，故名得使。”');
      }
      // 凶格：二吉四凶之四凶与诸格
      const PAIR = {
        乙辛: ['青龙逃走', '《烟波》：“乙加辛兮龙逃走。”《宝鉴》卷一：“乙木下临辛金，金克其木，木不能安，故凶。”'],
        辛乙: ['白虎猖狂', '《烟波》：“辛加乙兮虎猖狂。”'],
        丁癸: ['朱雀投江', '《宝鉴》卷一：“丁火下临癸水，火入水乡，自投绝地，故凶。”'],
        癸丁: ['螣蛇夭矫', '《烟波》：“癸加丁兮蛇夭矫。”'],
        庚丙: ['太白入荧', '《烟波》：“太白入荧贼即来。”（利客不利主）'],
        丙庚: ['荧入太白', '《烟波》：“荧入太白贼须灭。”（利主不利客）'],
        庚癸: ['大格', '《烟波》：“庚加癸兮为大格。”《宝鉴》：“主车破马伤，行人不至，官事不止。”'],
        庚壬: ['小格', '《烟波》：“加壬之时名上格〔一作小格〕。”《宝鉴》：“亦名移荡格，主远行迷失道路。”'],
        庚己: ['刑格', '《烟波》：“又嫌六庚加六己，名曰刑格主官司。”'],
      };
      const hit = PAIR[a.s + b.s];
      if (hit) add(p, hit[0], '凶', ['各书一致'], at, hit[1]);
      if (a.s === '己' && b.s === '庚') add(p, '刑格（返名）', '凶', ['《秘笈》十干克应'], at, '《秘笈》卷二：“加庚名曰‘刑格’……求名、词讼先动者不利。”');
      // 悖格：天盘丙加地盘之年、月、日、时干（甲换作该柱旬首之仪）
      // 寄干参与与否由设置决定（默认不参与：值符为天芮的旬里，寄干每个时辰都落在时干上）
      if (a.s === '丙' && (C.opts.beiJi || (!a.ji && !b.ji))) {
        const hitP = ['year', 'month', 'day', 'hour'].filter((k) => panStem(gzIndex(S.pillars[k])) === b.s);
        if (hitP.length) add(p, '悖格', '凶', ['《烟波》《宝鉴》（丙加年月日时干）'], `${at}，地盘${b.s}为${hitP.map((k) => ({ year: '年', month: '月', day: '日', hour: '时' })[k]).join('、')}干`, '《宝鉴》卷一：“丙加年、月、日、时干为悖格，盖丙为威权之火，加于四干之上，主纲纪紊乱，下逆其上。”又《宝鉴》卷一《释勃格飞伏》辨之：“诸书浑言勃格，与岁月日时干互相加临为飞伏，非也……若浑言岁月日时干，是以反首、跌穴，亦为勃伏、勃飞矣！”');
      }
    }
    for (const [a, b] of pairs(q)) {
      const at = `天盘${a.s}${jiT(a)}加地盘${b.s}${jiT(b)}`;
      // 奇仪伏吟、反吟
      if (a.s === b.s && S.tian.shift !== 0) add(p, '奇仪伏吟', '凶', ['各书一致'], at, '《烟波》：“就中伏吟最为凶。”');
      if (CHONG[a.s] === b.s) add(p, '奇仪反吟', '凶', ['各书一致（所遁六甲相冲）'], `${at}（${YI_ZHI[a.s]}${YI_ZHI[b.s]}相冲）`, '《烟波》：“天蓬若到天英上，须知即是反吟宫。”');
      // 飞干、伏干
      if (b.s === '庚' && a.s !== '庚' && ps.day.includes(a.s)) add(p, '飞干格', '凶', ['各书一致'], `${at}，天盘${a.s}为日干${S.pillars.day[0] === '甲' ? '（甲日取所遁之仪或戊）' : ''}`, '《宝鉴》卷一《释诸格》：“日干加庚为飞干格，庚加日干为伏干格。主客皆伤，尤不利主。”');
      if (a.s === '庚' && b.s !== '庚' && ps.day.includes(b.s)) add(p, '伏干格', '凶', ['各书一致'], `${at}，地盘${b.s}为日干${S.pillars.day[0] === '甲' ? '（甲日取所遁之仪或戊）' : ''}`, '《烟波》：“庚加日干伏干格。”《宝鉴》卷一：“庚加日干为伏干格。”');
      // 值符飞宫、天乙伏宫
      if (b.s === '庚' && a.s !== '庚' && (a.s === xunYi || a.s === '戊')) {
        const says = []; if (a.s === xunYi) says.push('《烟波》《宝鉴》（当旬值符之仪加庚）'); if (a.s === '戊') says.push('《秘笈》《统宗》十干克应常例（戊加庚）');
        add(p, '值符飞宫', '凶', says, at, '《烟波》：“直符加庚天乙飞。”《宝鉴》卷一：“直符加庚为飞宫格，主客皆不利，大凶。”');
      }
      if (a.s === '庚' && b.s !== '庚' && (b.s === xunYi || b.s === '戊')) {
        const says = []; if (b.s === xunYi) says.push('《烟波》《宝鉴》（庚加当旬值符之仪）'); if (b.s === '戊') says.push('《秘笈》《统宗》十干克应常例（庚加戊）');
        add(p, '天乙伏宫', '凶', says, at, '《烟波》：“庚加直符天乙伏。”《宝鉴》卷一：“庚加直符为伏宫格，主客皆不利，大凶。”');
      }
      // 岁、月、日、时四格：庚加四柱之干
      // 甲申柱遁庚，庚加庚归入十干克应“太白同宫（战格）”，不再重复标四格
      if (a.s === '庚' && b.s !== '庚') for (const k of ['year', 'month', 'day', 'hour']) if (ps[k].includes(b.s)) {
        add(p, { year: '岁格', month: '月格', day: '日格', hour: '时格' }[k], '凶', ['《烟波》《宝鉴》《统宗》'], `${at}，地盘${b.s}为${PILLAR_NAME[k]}干${S.pillars[k][0] === '甲' ? '（甲取所遁之仪或戊）' : ''}`, '《烟波》：“加着年干为岁格，月干月格日日格，时干之上名时格。”《宝鉴》卷一：“皆凶。”');
      }
      // 天网四张（十干克应说）、地网
      if (a.s === '癸' && b.s === '癸') add(p, '天网四张', '凶', ['《秘笈》《统宗》十干克应（癸加癸）'], at, '《秘笈》卷二：“癸加癸为天网四张，行人失伴，病讼皆伤。”');
      if (a.s === '己' && b.s === '壬') add(p, '地网高张', '凶', ['《秘笈》《统宗》十干克应'], at, '《秘笈》卷二：“己加壬名曰地网高张，狡童佚女，奸情杀伤。”');
      if (a.s === '壬' && b.s === '壬') add(p, '蛇入地罗', '凶', ['《秘笈》《统宗》十干克应'], at, '《秘笈》卷二：“壬加壬为蛇入地罗，外人缠绕，内事索索。”');
    }
    // 门迫、门制（门克宫为迫，宫克门为制）
    if (q.door) {
      const dw = DOOR_WX[q.door], pw = q.P.wx, jm = JIMEN.includes(q.door);
      if (KE5[dw] === pw) add(p, `门迫（${q.door}）`, '凶', ['各书一致'], `${q.door}属${dw}，克${q.P.gua}宫${pw}；${jm ? '吉门被迫' : '凶门被迫'}`, jm ? '《秘笈》卷十五：“吉门被迫吉不就。”《宝鉴》：“吉门被迫，吉事成凶。”' : '《秘笈》卷十五：“凶门被迫祸重重。”《宝鉴》：“凶门被迫，凶灾愈甚。”');
      if (KE5[pw] === dw) add(p, `门受制（${q.door}）`, '平', ['《烟波》《统宗》'], `${q.P.gua}宫${pw}克${q.door}${dw}`, '《烟波》：“宫制其门不为迫。”');
    }
    // 欢怡：三奇临当旬值符之仪，或与值符神同宫
    for (const a of q.sky) if (SANQI.includes(a.s)) {
      const viaEarth = q.hasEarth(xunYi), viaGod = q.god === '值符';
      if (viaEarth || viaGod) add(p, '欢怡', '吉', ['《统宗》'], `天盘${a.s}${jiT(a)}${viaEarth ? `临当旬值符之仪${xunYi}` : '与值符同宫'}`, '《统宗》：“三奇临六甲值符，名曰欢怡，利干贵求喜。”');
    }
    // ── 门、神组合类 ──
    const sk = (x) => q.hasSky(x), ea = (x) => q.hasEarth(x), dr = q.door, gd = q.god;
    // 玉女守门：地盘丁临值使门（正宗）；天盘丁临值使门（后世）
    // 值使落中五寄宫时，看的是中五的地盘干，不是寄宫本宫的干
    const rawP = S.door.doorTargetRaw, diAtShi = C.palaces[rawP].di;
    const yuEarth = p === S.door.doorTarget && diAtShi === '丁';
    if (dr === zhishi && (yuEarth || sk('丁'))) {
      const says = []; if (yuEarth) says.push('《烟波》《宝鉴》《统宗》《秘笈》（地盘丁临值使门）'); if (sk('丁')) says.push('近人（天盘丁临值使门）');
      add(p, '玉女守门', '吉', says, `值使${zhishi}临${yuEarth ? '地盘丁' : '天盘丁'}`, '《烟波》：“更有一般奇特处，六丁正好直使门。”《宝鉴》卷一：“玉女守门者，丁奇临直使之门也。”');
    }
    // 九遁
    const dun = (name, says, why, quote) => add(p, name, '吉', says, why, quote);
    if (sk('丙') && dr === '生门' && ea('丁')) dun('天遁', ['《烟波》《宝鉴》《统宗》'], '天盘丙、生门、地盘丁', '《烟波》：“生门六丙合六丁，此为天遁自分明。”');
    else if (sk('丙') && ea('丁') && JIMEN.includes(dr)) dun('天遁', ['《秘笈》十干克应（丙加丁得三吉门）'], `天盘丙加地盘丁，临${dr}`, '《秘笈》卷二：“加丁为‘月奇朱雀’……得三吉门为‘天遁’。”');
    if (sk('乙') && dr === '开门' && ea('己')) dun('地遁', ['《烟波》《宝鉴》《统宗》'], '天盘乙、开门、地盘己', '《烟波》：“开门六乙合六己，地遁如斯而已矣。”');
    else if (sk('乙') && ea('己') && JIMEN.includes(dr)) dun('地遁', ['《秘笈》十干克应（乙加己得三吉门）'], `天盘乙加地盘己，临${dr}`, '《秘笈》卷二：“加己为‘日奇入雾’……得三吉门为‘地遁’。”');
    if (sk('丁') && dr === '休门' && gd === '太阴') dun('人遁', ['《烟波》《宝鉴》《统宗》'], '天盘丁、休门、太阴', '《烟波》：“休门六丁共太阴，欲求人遁无过此。”');
    if (p === 4 && ((sk('乙') && JIMEN.includes(dr)) || (sk('丙') && dr === '开门'))) {
      const says = []; if (sk('乙') && JIMEN.includes(dr)) says.push('《统宗》《秘笈》（乙奇合三吉门临巽）'); if (sk('丙') && dr === '开门') says.push('《宝鉴》（丙奇合开门临巽）');
      dun('风遁', says, `巽四宫，${dr}`, '《宝鉴》卷一：“丙奇合开门临巽宫，名曰风遁；一云乙奇得开休生三门临巽宫者是。”');
    }
    if (sk('乙') && JIMEN.includes(dr) && (ea('辛') || p === 2)) {
      const says = []; if (ea('辛')) says.push('一说临六辛'); if (p === 2) says.push('一说临坤宫');
      dun('云遁', says, `天盘乙合${dr}${ea('辛') ? '，临地盘辛' : ''}${p === 2 ? '，在坤二宫' : ''}`, '《宝鉴》卷一：“乙奇合开休生三吉门临六辛，名曰云遁；一云临坤宫者是。”');
    }
    if (sk('乙') && JIMEN.includes(dr) && (p === 1 || ea('癸'))) {
      const says = [dr === '休门' ? '《宝鉴》（乙合休门）' : '一作开休生三吉门']; if (p === 1) says.push('临坎宫'); if (ea('癸')) says.push('临六癸');
      dun('龙遁', says, `天盘乙合${dr}${p === 1 ? '，在坎一宫' : ''}${ea('癸') ? '，临地盘癸' : ''}`, '《宝鉴》卷一：“乙奇合休门临坎宫，或临六癸，名曰龙遁。”');
    }
    {
      // 虎遁：《宝鉴》《统宗》按“或”（临六辛或临艮宫）；《秘笈》卷六三组须同时具备
      const says = [];
      if (sk('乙') && (dr === '休门' || dr === '生门') && (ea('辛') || p === 8)) says.push(`《宝鉴》《统宗》（乙奇合${dr}，${ea('辛') ? '临六辛' : '临艮宫'}）`);
      if (dr === '开门' && sk('庚') && p === 7) says.push('《秘笈》（开门、庚，临兑宫）');
      if ((dr === '休门' || dr === '生门') && sk('乙') && ea('辛') && p === 8) says.push(`《秘笈》（${dr}、乙奇加地盘辛于艮宫）`);
      if (dr === '生门' && sk('辛') && ea('乙') && p === 8) says.push('《秘笈》（生门、辛加地盘乙于艮宫）');
      if (says.length) dun('虎遁', says, `${dr}，${G(q)}`, '《秘笈》卷六《九遁变化法》：“开门、甲申庚，下临地盘兑宫为‘虎遁’。或休门、乙奇加地盘六辛于艮宫，或生门、辛加地盘于乙、艮宫，亦皆名‘虎遁’。”《统宗》卷一：“休门与乙奇合艮、辛。”');
    }
    if (sk('丙') && dr === '生门' && gd === '九天') dun('神遁', ['各书一致'], '天盘丙、生门、九天', '《宝鉴》卷一：“天上丙奇，得生门，合九天临之，名曰神遁。”');
    if (sk('丁') && gd === '九地' && ['杜门', '休门', '生门'].includes(dr)) {
      const says = dr === '休门' ? ['《宝鉴》（丁奇、休门、九地）'] : ['《秘笈》《统宗》（丁奇、' + dr + '、九地）'];
      dun('鬼遁', says, `天盘丁、${dr}、九地`, '《宝鉴》卷一：“天上丁奇，得休门，合九地临之，名曰鬼遁。”《秘笈》卷五：“丁奇、杜门、九地为鬼遁。”');
    }
    // 三诈
    if (SANQI.some(sk) && JIMEN.includes(dr)) {
      const zha = { 太阴: '真诈', 六合: '休诈', 九地: '重诈' }[gd];
      if (zha) add(p, zha, '吉', ['《秘笈》《统宗》《宝鉴》一致'], `三奇（${SANQI.filter(sk).join('')}）合${dr}，临${gd}`, '《宝鉴》卷一：“三奇合开、休、生三门，临太阴为真诈，临六合为休诈，临九地为重诈。”');
    }
    // 五假
    const any = (arr) => arr.some(sk);
    if (dr === '景门' && any(SANQI) && gd === '九天') add(p, '天假', '吉', ['《宝鉴》'], `景门合三奇，临九天`, '《宝鉴》卷一：“景门合乙丙丁临九天为天假。”');
    if (dr === '杜门' && any(['丁', '己', '癸']) && SANYIN.includes(gd)) add(p, '地假', '吉', gd === '九地' ? ['《宝鉴》《秘笈》《统宗》'] : ['《秘笈》《统宗》（兼取太阴、六合）'], `杜门合${['丁', '己', '癸'].filter(sk).join('')}，临${gd}`, '《宝鉴》卷一：“杜门合丁己癸临九地为地假。”');
    if (dr === '惊门' && sk('壬') && gd === '九天') add(p, '人假', '吉', ['《宝鉴》'], '惊门合壬，临九天', '《宝鉴》卷一：“惊门合六壬临九天为人假。”');
    if (dr === '伤门' && any(['丁', '己', '癸']) && (gd === '九地' || gd === '六合')) add(p, '神假', '吉', gd === '九地' ? ['《宝鉴》'] : ['一说兼取六合'], `伤门合${['丁', '己', '癸'].filter(sk).join('')}，临${gd}`, '《宝鉴》卷一：“伤门合丁己癸临九地为神假。”');
    if (dr === '死门' && any(['丁', '己', '癸']) && gd === '九地') add(p, '鬼假', '吉', ['《宝鉴》'], `死门合${['丁', '己', '癸'].filter(sk).join('')}，临九地`, '《宝鉴》卷一：“死门合丁己癸临九地为鬼假。”');
    // 阳门得助：三吉门得三阴神
    if (JIMEN.includes(dr) && SANYIN.includes(gd)) add(p, '阳门得助', '吉', ['《秘笈》卷五《三诈法》'], `${dr}得${gd}`, '《秘笈》卷五：“有地盘〔转盘作神盘〕九地、太阴、六合三神助奇，谓之‘阳门得助’。”');
    // 奇游禄位 / 三奇升殿
    const LU = { 乙: 3, 丙: 4, 丁: 9 };
    for (const a of q.sky) if (LU[a.s] === p) {
      const withMen = JIMEN.includes(dr);
      add(p, withMen ? '奇游禄位' : '三奇升殿', '吉', ['各书一致'], `天盘${a.s}${jiT(a)}落${G(q)}${withMen ? '，又合' + dr : ''}`, '《统宗》《秘笈》：“乙奇到震、丙奇到巽、丁奇到离，此为三奇游禄位，若合三吉门，百事大吉。”');
    }
    // 六仪击刑：当旬值符所遁之仪为重
    for (const a of q.sky) if (XING_GONG[a.s] === p) {
      const zf = a.s === xunYi;
      add(p, zf ? '值符击刑' : '六仪击刑', '凶', zf ? ['《烟波》《宝鉴》本义（当旬值符）', '通行法'] : ['通行法（不论是否值符）'], `天盘${a.s}${jiT(a)}落${G(q)}`, '《烟波》：“六仪击刑何太凶，甲子直符愁向东。戌刑在未申刑虎，寅巳辰辰午刑午。”');
    }
    // 三奇入墓
    for (const a of q.sky) {
      const says = [];
      if (a.s === '丙' && p === 6) says.push('各书一致（火墓在戌）');
      if (a.s === '丁' && p === 6) says.push('《宝鉴》（火墓在戌）');
      if (a.s === '丁' && p === 8) says.push('阴阳分论派（阴火墓丑）');
      if (a.s === '乙' && p === 2) says.push('五行通墓（木墓在未）');
      if (a.s === '乙' && p === 6) says.push('《宝鉴》《统宗》《秘笈》（乙长生午、墓戌）');
      if (says.length) add(p, '三奇入墓', '凶', says, `天盘${a.s}${jiT(a)}落${G(q)}`, '《宝鉴》卷一：“乙木长生在午，墓在戌，又木墓在未；丙火、丁火长生在寅，墓在戌。故乙临二、六宫，丙、丁临六宫，皆名三奇入墓。”');
    }
  }

  // ── 全局（四柱）──
  // 五不遇时以古籍所列十时为准（通则“时干克日干、阴阳相同”在庚日、己日会多出丙戌、乙亥两时，古籍不列）
  const BUYU = ['甲庚午', '乙辛巳', '丙壬辰', '丁癸卯', '戊甲寅', '己乙丑', '庚丙子', '辛丁酉', '壬戊申', '癸己未'];
  if (BUYU.includes(S.pillars.day[0] + S.pillars.hour)) add(0, '五不遇时', '凶', ['各书一致'], `${S.pillars.day[0]}日${S.pillars.hour}时，时干${S.pillars.hour[0]}克日干${S.pillars.day[0]}，阴阳相同`, '《烟波》：“五不遇时龙不精，号为日月损光明。时干来克日干上，甲日须知时忌庚。”');
  if (['丙戌', '壬辰', '癸未', '戊戌', '己丑', '丁丑'].includes(S.pillars.hour)) add(0, '时干入墓', '凶', ['《统宗》《秘笈》《宝鉴》（六干入墓之时）'], `时柱${S.pillars.hour}`, '《宝鉴》卷一：“又有六干入墓：戊戌、己丑、丙戌、丁丑、壬辰、癸未时也。时干入墓，凡事皆暗昧不明。”');
  const hourStem = S.pillars.hour[0];
  if (hourStem === '癸') {
    // 天网：看天上（天盘）癸临何宫，各家高低之说并列
    const tps = [4, 9, 2, 3, 7, 8, 1, 6].filter((k) => C.palaces[k].tianStems.includes('癸'));
    for (const tp of tps) {
      const yb = { 1: '网低，有路通', 2: '网低，有路通', 3: '行入墓', 4: '行入墓', 8: '高张，任西东', 9: '高张，任西东' }[tp] || '歌中未言';
      const bj = tp === 4 ? '入墓，不宜出' : tp === 6 ? '触冠，不宜出' : tp <= 3 ? '网低，两臂负刀俯身匍匐而去' : '网高，仰面踽步而去';
      const tz = tp <= 5 ? '尺寸低' : '尺寸高';
      add(0, '天网四张', '凶', ['《烟波》《宝鉴》《统宗》（六癸之时）'],
        `时干癸，天盘癸临${C.palaces[tp].gua}${tp}宫。《烟波》：${yb}；《宝鉴·释天网》：${bj}；《统宗》：${tz}${S.pillars.hour === '癸亥' ? '。癸亥时，《宝鉴》另称“东西南北皆无路可出，惟阳九局、阴一局有之”' : ''}`,
        '《烟波》：“天网四张无路走，一二网低有路通；三至四宫行入墓，八九高张任西东。”《宝鉴》卷一《释天网》：“视天上癸临何宫：临四宫为入墓，不宜出；临一、二、三宫为低；临六宫为触冠，不宜出；临七、八、九宫为高。”《统宗》卷一：“一、二、三、四、五宫尺寸低，六、七、八、九宫尺寸高。”');
    }
  }
  if (hourStem === '壬') {
    const tps = [4, 9, 2, 3, 7, 8, 1, 6].filter((k) => C.palaces[k].tianStems.includes('壬'));
    add(0, '地网遮蔽', '凶', ['《烟波》古注（六壬之时）'], `时干壬${tps.length ? `，天盘壬临${tps.map((k) => C.palaces[k].gua + k + '宫').join('、')}` : ''}`, '《烟波》古注：“六壬为地网，六癸为天网。”');
  }
  // 天辅三说：天显时格（六甲时）、《三元经》天辅之时、五合时
  const dG = S.pillars.day[0], hG = hourStem;
  if (hG === '甲') add(0, '天显时格（六甲天辅时）', '吉', ['《宝鉴》卷一'], `时柱${S.pillars.hour}`, '《宝鉴》卷一《释天辅时与五合时同吉异理》：“天辅时者：甲子、甲戌、甲申、甲午、甲辰、甲寅时也……经云：‘天辅之时，有罪无疑，斧钺在前，天犹赦之。’……凡值此时，宜雪冤理枉，解纷释难，诸事皆吉。”');
  const SANYUAN = { 甲: '己巳', 己: '己巳', 乙: '甲申', 庚: '甲申', 丙: '甲午', 辛: '甲午', 丁: '甲辰', 壬: '甲辰', 戊: '甲寅', 癸: '甲寅' };
  if (SANYUAN[dG] === S.pillars.hour) add(0, '天辅之时', '吉', ['《秘笈》卷一引《三元经》'], `${dG}日${S.pillars.hour}时`, '《秘笈》卷一：“甲己日己巳时，乙庚日甲申时，丙辛日甲午时，丁壬日甲辰时，戊癸日甲寅时，是为天辅之时，此时有罪自释。”');
  const HE = { 甲: '己', 己: '甲', 乙: '庚', 庚: '乙', 丙: '辛', 辛: '丙', 丁: '壬', 壬: '丁', 戊: '癸', 癸: '戊' };
  if (HE[dG] === hG) add(0, '五合时（林氏天辅时）', '吉', ['《宝鉴》卷一'], `日干${dG}与时干${hG}相合`, '《宝鉴》卷一：“五合时者，时与日之干相合也……凡值此时，吉神用事，凶煞退藏，故其吉与天辅时同。宜谋为和合、隐秘诸事，不宜雪理解释。故曰：同吉异理。林氏以五合时为天辅时，谓五合吉时，对五不遇凶时也。”');
  return out;
}
